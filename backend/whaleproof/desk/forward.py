"""Forward record: the live signals (from Sep 30, 2026) as a committed, derived file, so anyone can read the paper-trading
record without our cache. Stock results only; per-alert UW fields (premium, contract, strike, spot) stay in the local
cache (UW data is not redistributed). Exploratory: a record, not proof."""
from __future__ import annotations

import statistics as st
from datetime import date

from .tracker import LIVE_PERIOD

TYPE = {"whale": "Whale bet", "far_otm": "Far-OTM buy"}
STATUS = {"closed": "finished", "open": "open", "waiting": "waiting for entry"}


def forward_record(rows: list[dict], as_of: str) -> dict:
    sigs = [{"flow_day": r["session_date"], "ticker": r["ticker"], "type": TYPE.get(r["tier"], r["tier"]),
             "direction": "bullish" if r["direction"] > 0 else "bearish", "buy_open": r["entry_on"],
             "sell_close": r["exit_by"], "status": STATUS.get(r["stock"]["status"], r["stock"]["status"]),
             "days_held": r["stock"].get("days_held"), "stock_return": r["stock"].get("ret"),
             "vs_sp500": r["stock"].get("vs_spy")}
            for r in rows if r["period"] == LIVE_PERIOD]
    sigs.sort(key=lambda s: (s["flow_day"], s["ticker"]))
    done = [s for s in sigs if s["status"] == "finished" and s["stock_return"] is not None]
    vs = [s["vs_sp500"] for s in done if s["vs_sp500"] is not None]
    return {"label": "exploratory forward record (live, after the rules were frozen); not proof", "as_of": as_of,
            "period": LIVE_PERIOD, "rule": "buy the stock at the next open, sell at the close of the 5th session, "
            "0.10% costs; vs S&P 500 over the same days",
            "summary": {"signals": len(sigs), "finished": len(done), "open": len(sigs) - len(done),
                        "won": sum(s["stock_return"] > 0 for s in done),
                        "avg_stock_return": st.fmean(s["stock_return"] for s in done) if done else None,
                        "avg_vs_sp500": st.fmean(vs) if vs else None, "beat_sp500": sum(v > 0 for v in vs)},
            "signals": sigs}


def _pct(v: float | None) -> str:
    return "–" if v is None else f"{v * 100:+.2f}%".replace("-", "−")      # true minus, as in the app


def _times(n: int) -> str:
    return f"{n} time" if n == 1 else f"{n} times"


def _day(s: str) -> str:
    d = date.fromisoformat(s)
    return f"{d:%b} {d.day}"


def markdown(rec: dict) -> str:
    sm = rec["summary"]
    out = ["# Forward record (live signals)", "",
           f"Signals WhaleProof flagged after the rules were frozen, from Sep 30, 2026. Updated {rec['as_of'][:16].replace('T', ' ')} UTC.",
           f"Rule: {rec['rule']}. Generated by `uv run whaleproof forward` from the local cache; stock results only.", "",
           "**Exploratory: a record, not proof.** Fewer than 30 finished trades is noise; see the How it works page for the "
           "tested periods.", ""]
    if not rec["signals"]:
        return "\n".join(out + ["No live signals yet.", ""])
    head = (f"**{sm['finished']} finished** · {sm['open']} open or waiting · won {sm['won']} of {sm['finished']} · "
            f"average {_pct(sm['avg_stock_return'])} per trade · {_pct(sm['avg_vs_sp500'])} vs S&P 500 · "
            f"beat the S&P 500 {_times(sm['beat_sp500'])}") if sm["finished"] else \
        f"**No finished trades yet** · {sm['open']} open or waiting"
    out += [head, "",
            "| Flow day | Ticker | Type | Buy (open) | Sell (close) | Status | Stock | vs S&P 500 |",
            "|---|---|---|---|---|---|---|---|"]
    for s in reversed(rec["signals"]):
        out.append(f"| {_day(s['flow_day'])} | {s['ticker']} | {s['type']} | {_day(s['buy_open'])} | "
                   f"{_day(s['sell_close'])} | {s['status']} | {_pct(s['stock_return'])} | {_pct(s['vs_sp500'])} |")
    return "\n".join(out + ["", "Not financial advice.", ""])
